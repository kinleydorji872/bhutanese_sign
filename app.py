from pathlib import Path
import io
import json
import os

from flask import Flask, jsonify, render_template, request
from PIL import Image, UnidentifiedImageError

BASE_DIR = Path(__file__).resolve().parent
MODEL_DIR = BASE_DIR / "models"
MAX_UPLOAD_BYTES = 4 * 1024 * 1024
IMAGE_SIZE = (64, 64)

# Vercel detects this top-level WSGI object.
app = Flask(__name__, template_folder="templates", static_folder="static")
app.config["MAX_CONTENT_LENGTH"] = MAX_UPLOAD_BYTES


def load_model(mode):
    model_path = MODEL_DIR / f"{mode}.keras"
    labels_path = MODEL_DIR / f"{mode}_labels.json"
    if not model_path.is_file() or not labels_path.is_file():
        return None, None
    try:
        import tensorflow as tf
        model = tf.keras.models.load_model(model_path)
        labels = json.loads(labels_path.read_text(encoding="utf-8"))
        return model, labels
    except ImportError as exc:
        raise RuntimeError(
            "TensorFlow is not installed on this server. Install the ML dependencies "
            "on a compatible Python inference host."
        ) from exc
    except Exception as exc:
        raise RuntimeError(f"Could not load the {mode} model: {exc}") from exc


@app.get("/")
def home():
    return render_template("index.html")


@app.get("/api/health")
def health():
    return jsonify({
        "status": "ok",
        "models": {
            mode: {
                "available": (MODEL_DIR / f"{mode}.keras").is_file()
                and (MODEL_DIR / f"{mode}_labels.json").is_file()
            }
            for mode in ("digits", "alphabet")
        },
    })


@app.errorhandler(413)
def upload_too_large(_error):
    return jsonify(error="Image is too large. Maximum upload size is 4 MB."), 413


@app.post("/api/predict")
def predict():
    mode = request.form.get("mode", "digits").strip().lower()
    if mode not in {"digits", "alphabet"}:
        return jsonify(error="Invalid category. Choose digits or alphabet."), 400
    upload = request.files.get("image")
    if upload is None or not upload.filename:
        return jsonify(error="Choose an image before submitting."), 400
    raw = upload.read(MAX_UPLOAD_BYTES + 1)
    if not raw:
        return jsonify(error="The uploaded image is empty."), 400
    if len(raw) > MAX_UPLOAD_BYTES:
        return jsonify(error="Image is too large. Maximum upload size is 4 MB."), 413
    try:
        with Image.open(io.BytesIO(raw)) as source:
            if source.format not in {"JPEG", "PNG", "WEBP"}:
                return jsonify(error="Use a JPG, PNG, or WEBP image."), 415
            if source.width * source.height > 20_000_000:
                return jsonify(error="Image dimensions are too large."), 413
            image = source.convert("RGB").resize(IMAGE_SIZE)
    except (UnidentifiedImageError, OSError, ValueError):
        return jsonify(error="Invalid image. Please choose a JPG, PNG, or WEBP file."), 400
    try:
        model, labels = load_model(mode)
    except RuntimeError as exc:
        return jsonify(error=str(exc)), 503
    if model is None:
        return jsonify(error=f"No trained {mode} model is installed yet. See README.md to train one."), 503
    import numpy as np
    batch = np.expand_dims(np.asarray(image, dtype=np.float32) / 255.0, axis=0)
    scores = model.predict(batch, verbose=0)[0]
    index = int(np.argmax(scores))
    confidence = float(scores[index])
    if isinstance(labels, list):
        predicted = str(labels[index]) if index < len(labels) else str(index)
    else:
        predicted = str(labels.get(str(index), labels.get(index, index)))
    return jsonify({
        "label": predicted if confidence >= 0.70 else "Uncertain",
        "predicted_label": predicted,
        "confidence": confidence,
        "message": (
            "Low confidence. Try a clearer image with one hand visible."
            if confidence < 0.70 else "Prediction generated by your trained model."
        ),
    })


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=int(os.environ.get("PORT", "5000")), debug=False)
